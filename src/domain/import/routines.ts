/**
 * Reconstructing routines from a history that does not contain any (IMPORT.md).
 *
 * This is the part of the import Hevy does not do at all — it drops routines —
 * and the reason a switcher gets their plan back rather than just their numbers.
 *
 * The rule originally specified (identical **ordered** exercise set, seen ≥3
 * times) was measured against the real fixtures on 15 Sep and found far too
 * strict: 6 candidates covering 34/86 Strong sessions, and **1 covering 3/80**
 * on Hevy. Set order drifts week to week, which the exact rule cannot survive.
 *
 * So, in order:
 *   1. Group by title where the title means something.
 *   2. Group whatever is left by exercise overlap, not exact match.
 *   3. Anything seen three times is a candidate; the user unticks what they
 *      do not want.
 */

import { normaliseName } from '../normalise';
import type { ParsedRoutine, ParsedSession } from './types';

/**
 * Titles the source app generated, which name nothing.
 *
 * 73 of 86 sessions in the real Strong log are "Evening Workout"; Hevy emits
 * "Morning workout ☀️". Naming a routine from those produces a routine called
 * Evening Workout, which is noise wearing a name.
 */
const AUTOGENERATED = /^(morning|afternoon|evening|midday|night|quick|new)?\s*workout\s*\d*$/i;

export function isMeaningfulTitle(title: string | null | undefined): boolean {
  if (!title) return false;
  // \uFE0F is the variation selector that follows many emoji; stripping the
  // pictograph alone leaves it behind and the trim does not remove it, so
  // "Morning workout ☀️" stayed unmatched.
  const text = title
    .replace(/[\p{Emoji_Presentation}\p{Extended_Pictographic}\uFE0F\u200D]/gu, '')
    .trim();
  if (text.length < 2) return false;
  return !AUTOGENERATED.test(text);
}

/** Distinct exercises in a session, normalised, order discarded. */
function exerciseSet(session: ParsedSession): Set<string> {
  return new Set(session.sets.map((set) => normaliseName(set.exerciseName)));
}

export function jaccard(a: ReadonlySet<string>, b: ReadonlySet<string>): number {
  if (a.size === 0 || b.size === 0) return 0;
  let shared = 0;
  for (const value of a) if (b.has(value)) shared += 1;
  return shared / (a.size + b.size - shared);
}

/** Exercises in the order they most often appear, across a group of sessions. */
function representativeOrder(sessions: readonly ParsedSession[]): string[] {
  const best = [...sessions].sort((x, y) => y.sets.length - x.sets.length)[0];
  if (!best) return [];
  const seen = new Set<string>();
  const out: string[] = [];
  for (const set of best.sets) {
    const key = normaliseName(set.exerciseName);
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(set.exerciseName);
  }
  return out;
}

function median(values: number[]): number {
  if (values.length === 0) return 3;
  const sorted = [...values].sort((a, b) => a - b);
  const middle = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 0
    ? Math.round(((sorted[middle - 1] ?? 3) + (sorted[middle] ?? 3)) / 2)
    : sorted[middle] ?? 3;
}

/** Median number of working sets per exercise across the group. */
function targetSets(sessions: readonly ParsedSession[], names: readonly string[]): number[] {
  return names.map((name) => {
    const key = normaliseName(name);
    const counts = sessions.map((session) =>
      session.sets.filter((set) => normaliseName(set.exerciseName) === key && set.type !== 'warmup').length,
    ).filter((count) => count > 0);
    return Math.max(1, median(counts));
  });
}

const MIN_OCCURRENCES = 3;

/**
 * 0.6, not the 0.7 first written down.
 *
 * Jaccard punishes small sessions: swapping one exercise in a six-exercise day
 * scores 5/7 = 0.71, but the same single swap in a four-exercise day scores
 * 3/5 = 0.6. Both are obviously the same routine to the lifter, and a
 * four-exercise day is the common case. Two genuinely different days share
 * almost nothing, so the looser threshold costs no precision here.
 */
const MIN_SIMILARITY = 0.6;

export interface InferenceOptions {
  readonly minOccurrences?: number;
  readonly minSimilarity?: number;
}

/**
 * Routine candidates, most-repeated first.
 *
 * Named from the title when the group has a meaningful one, otherwise
 * `Routine A`, `Routine B` — never from an autogenerated title.
 */
export function inferRoutines(
  sessions: readonly ParsedSession[],
  options: InferenceOptions = {},
): ParsedRoutine[] {
  const minCount = options.minOccurrences ?? MIN_OCCURRENCES;
  const minSimilarity = options.minSimilarity ?? MIN_SIMILARITY;

  const groups: { key: string | null; sessions: ParsedSession[]; sets: Set<string> }[] = [];
  const byTitle = new Map<string, ParsedSession[]>();
  const untitled: ParsedSession[] = [];

  for (const session of sessions) {
    if (session.sets.length === 0) continue;
    if (isMeaningfulTitle(session.title)) {
      const key = normaliseName(session.title as string);
      const list = byTitle.get(key);
      if (list) list.push(session);
      else byTitle.set(key, [session]);
    } else {
      untitled.push(session);
    }
  }

  for (const [key, list] of byTitle) {
    groups.push({ key, sessions: list, sets: exerciseSet(list[0] as ParsedSession) });
  }

  /**
   * What is left is clustered by overlap. Each session joins the first cluster
   * it is similar enough to — a single pass, because a lifter's week has a
   * handful of shapes, not a taxonomy, and agglomerative clustering here would
   * be precision nobody can see.
   */
  for (const session of untitled) {
    const sets = exerciseSet(session);
    const match = groups.find((group) => group.key === null && jaccard(group.sets, sets) >= minSimilarity);
    if (match) match.sessions.push(session);
    else groups.push({ key: null, sessions: [session], sets });
  }

  const candidates = groups
    .filter((group) => group.sessions.length >= minCount)
    .sort((a, b) => b.sessions.length - a.sessions.length);

  let letter = 0;
  return candidates.map((group) => {
    const names = representativeOrder(group.sessions);
    const titled = group.sessions.find((session) => isMeaningfulTitle(session.title));
    const name = titled?.title ?? `Routine ${String.fromCharCode(65 + letter++)}`;
    return {
      name,
      exerciseNames: names,
      targetSets: targetSets(group.sessions, names),
      origin: 'inferred' as const,
    };
  });
}
